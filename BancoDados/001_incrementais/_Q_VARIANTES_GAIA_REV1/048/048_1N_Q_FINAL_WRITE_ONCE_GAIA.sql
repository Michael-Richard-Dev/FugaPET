-- Q NOVO:
-- somente estrutura 1:N; nenhum backfill/normalizacao historica HML.
--
-- ACL runtime final:
-- SELECT=SIM
-- INSERT=SIM
-- UPDATE=NAO
-- DELETE=NAO
--
-- Semantica: APPEND_ONLY / WRITE_ONCE.
-- Idempotencia:
-- UNIQUE(codigo_apontamento,tipo_processo,codigo_registro_processo).

BEGIN;

SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '120s';
SET LOCAL search_path = pg_catalog, homologacao;

DO $gaia_q_guard$
BEGIN
    IF current_database() <> 'fuga_jales_local_homologacao_q_v1_2' THEN
        RAISE EXCEPTION
            '048_Q_ABORT_DATABASE atual=% esperado=fuga_jales_local_homologacao_q_v1_2',
            current_database();
    END IF;

    IF current_user <> 'fugapet_q_owner' THEN
        RAISE EXCEPTION
            '048_Q_ABORT_CURRENT_USER atual=% esperado=fugapet_q_owner',
            current_user;
    END IF;

    IF session_user = 'fugapet_q_app' THEN
        RAISE EXCEPTION
            '048_Q_ABORT_RUNTIME_APP_NAO_PODE_EXECUTAR_DDL';
    END IF;

    IF to_regnamespace('homologacao') IS NULL THEN
        RAISE EXCEPTION '048_Q_ABORT_SCHEMA_HOMOLOGACAO_AUSENTE';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_roles
        WHERE rolname='fugapet_q_app'
          AND rolcanlogin
          AND NOT rolsuper
          AND NOT rolcreatedb
          AND NOT rolcreaterole
          AND NOT rolreplication
          AND NOT rolbypassrls
    ) THEN
        RAISE EXCEPTION
            '048_Q_ABORT_ROLE_APP_AUSENTE_OU_INSEGURA';
    END IF;

    IF to_regclass(
        'homologacao.operacao_producao_apontamento'
    ) IS NULL THEN
        RAISE EXCEPTION
            '048_Q_ABORT_DEPENDENCIA_039_AUSENTE';
    END IF;

    IF to_regclass(
        'homologacao.operacao_producao_apontamento_processo'
    ) IS NOT NULL THEN
        RAISE EXCEPTION
            '048_Q_ABORT_TABELA_1N_JA_EXISTE';
    END IF;
END
$gaia_q_guard$;

CREATE TABLE homologacao.operacao_producao_apontamento_processo (
    codigo_apontamento_processo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo_apontamento BIGINT NOT NULL,
    tipo_processo TEXT NOT NULL,
    codigo_registro_processo BIGINT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT operacao_producao_apontamento_processo_pkey
        PRIMARY KEY (codigo_apontamento_processo),

    CONSTRAINT fk_op_apontamento_processo_apontamento
        FOREIGN KEY (codigo_apontamento)
        REFERENCES homologacao.operacao_producao_apontamento (codigo_apontamento)
        ON DELETE RESTRICT,

    CONSTRAINT uq_op_apontamento_processo_tripla
        UNIQUE (codigo_apontamento, tipo_processo, codigo_registro_processo),

    CONSTRAINT ck_op_apontamento_processo_tipo_nao_vazio
        CHECK (btrim(tipo_processo) <> '')
);

-- ============================================================
-- ACL ROTA B — HERA FINAL
-- ============================================================

REVOKE ALL
ON TABLE homologacao.operacao_producao_apontamento_processo
FROM PUBLIC;

REVOKE ALL
ON TABLE homologacao.operacao_producao_apontamento_processo
FROM fugapet_q_app;

GRANT SELECT, INSERT
ON TABLE homologacao.operacao_producao_apontamento_processo
TO fugapet_q_app;

-- A coluna identity exige acesso funcional à sequence.
-- UPDATE da sequence permanece proibido.
DO $gaia_q_sequence_acl$
DECLARE
    v_sequence regclass;
BEGIN
    v_sequence :=
        pg_get_serial_sequence(
            'homologacao.operacao_producao_apontamento_processo',
            'codigo_apontamento_processo'
        )::regclass;

    IF v_sequence IS NULL THEN
        RAISE EXCEPTION
            '048_Q_ABORT_IDENTITY_SEQUENCE_NAO_RESOLVIDA';
    END IF;

    EXECUTE format(
        'REVOKE ALL ON SEQUENCE %s FROM PUBLIC',
        v_sequence
    );

    EXECUTE format(
        'REVOKE ALL ON SEQUENCE %s FROM fugapet_q_app',
        v_sequence
    );

    EXECUTE format(
        'GRANT USAGE, SELECT ON SEQUENCE %s TO fugapet_q_app',
        v_sequence
    );
END
$gaia_q_sequence_acl$;

-- ============================================================
-- ASSERTIONS FAIL-CLOSED
-- ============================================================

DO $gaia_q_postcheck$
DECLARE
    v_owner name;
    v_sequence regclass;
    v_sequence_owner name;
BEGIN
    SELECT pg_get_userbyid(c.relowner)
    INTO v_owner
    FROM pg_class c
    WHERE c.oid =
        'homologacao.operacao_producao_apontamento_processo'::regclass;

    IF v_owner IS DISTINCT FROM 'fugapet_q_owner' THEN
        RAISE EXCEPTION
            '048_Q_ABORT_OWNER_TABELA atual=% esperado=fugapet_q_owner',
            v_owner;
    END IF;

    IF NOT has_table_privilege(
        'fugapet_q_app',
        'homologacao.operacao_producao_apontamento_processo',
        'SELECT'
    ) THEN
        RAISE EXCEPTION '048_Q_ABORT_APP_SEM_SELECT';
    END IF;

    IF NOT has_table_privilege(
        'fugapet_q_app',
        'homologacao.operacao_producao_apontamento_processo',
        'INSERT'
    ) THEN
        RAISE EXCEPTION '048_Q_ABORT_APP_SEM_INSERT';
    END IF;

    IF has_table_privilege(
        'fugapet_q_app',
        'homologacao.operacao_producao_apontamento_processo',
        'UPDATE'
    ) THEN
        RAISE EXCEPTION '048_Q_ABORT_APP_COM_UPDATE';
    END IF;

    IF has_table_privilege(
        'fugapet_q_app',
        'homologacao.operacao_producao_apontamento_processo',
        'DELETE'
    ) THEN
        RAISE EXCEPTION '048_Q_ABORT_APP_COM_DELETE';
    END IF;

    IF has_table_privilege(
        'fugapet_q_app',
        'homologacao.operacao_producao_apontamento_processo',
        'TRUNCATE'
    ) OR
       has_table_privilege(
        'fugapet_q_app',
        'homologacao.operacao_producao_apontamento_processo',
        'REFERENCES'
    ) OR
       has_table_privilege(
        'fugapet_q_app',
        'homologacao.operacao_producao_apontamento_processo',
        'TRIGGER'
    ) THEN
        RAISE EXCEPTION
            '048_Q_ABORT_APP_PRIVILEGIO_DDL_INDEVIDO';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid =
            'homologacao.operacao_producao_apontamento_processo'::regclass
          AND conname =
            'uq_op_apontamento_processo_tripla'
          AND contype='u'
    ) THEN
        RAISE EXCEPTION
            '048_Q_ABORT_UNIQUE_IDEMPOTENCIA_AUSENTE';
    END IF;

    v_sequence :=
        pg_get_serial_sequence(
            'homologacao.operacao_producao_apontamento_processo',
            'codigo_apontamento_processo'
        )::regclass;

    IF NOT has_sequence_privilege(
        'fugapet_q_app',
        v_sequence,
        'USAGE'
    ) OR
       NOT has_sequence_privilege(
        'fugapet_q_app',
        v_sequence,
        'SELECT'
    ) OR
       has_sequence_privilege(
        'fugapet_q_app',
        v_sequence,
        'UPDATE'
    ) THEN
        RAISE EXCEPTION
            '048_Q_ABORT_SEQUENCE_ACL_DIVERGENTE';
    END IF;

    SELECT pg_get_userbyid(c.relowner)
    INTO v_sequence_owner
    FROM pg_class c
    WHERE c.oid=v_sequence;

    IF v_sequence_owner IS DISTINCT FROM 'fugapet_q_owner' THEN
        RAISE EXCEPTION
            '048_Q_ABORT_OWNER_SEQUENCE atual=% esperado=fugapet_q_owner',
            v_sequence_owner;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_class c
        CROSS JOIN LATERAL
            aclexplode(
                COALESCE(
                    c.relacl,
                    acldefault('r',c.relowner)
                )
            ) a
        WHERE c.oid =
            'homologacao.operacao_producao_apontamento_processo'::regclass
          AND a.grantee=0
    ) THEN
        RAISE EXCEPTION
            '048_Q_ABORT_PUBLIC_PRIVILEGE_TABELA';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM homologacao.operacao_producao_apontamento_processo
    ) THEN
        RAISE EXCEPTION
            '048_Q_ABORT_Q_NOVO_DEVE_INICIAR_SEM_BACKFILL_HML';
    END IF;
END
$gaia_q_postcheck$;

COMMIT;

