\set ON_ERROR_STOP on
-- ============================================================
-- 057_operacao_resultado_perfil_definicao_estrutura_DEV_PROPOSTA_GAIA.sql
-- FugaPET | Ambiente DEV | Schema desenvolvimento
-- Incremento 057 - Estrutura de operacao_resultado_perfil e operacao_resultado_definicao
-- PROPOSTA (APLICA DDL)
--
-- A procedencia, as diferencas declaradas e o escopo estao no PREFLIGHT deste mesmo
-- pacote. Em resumo: o DDL foi extraido do catalogo do banco de homologacao do Q, em
-- transacao READ ONLY, com autorizacao expressa do usuario, porque nao existe em
-- nenhum pacote deste repositorio. Somente estrutura; nenhuma linha vem do Q.
--
-- ORDEM OBRIGATORIA: operacao_resultado_definicao referencia operacao_resultado_perfil,
-- portanto o perfil e criado primeiro.
--
-- GRANT: SELECT para fugapet_dev_app, identico ao que o Q concede. O runtime le as
-- definicoes; nao as escreve. Fail-closed: sem INSERT, UPDATE ou DELETE.
--
--   SEM DML de negocio. NAO SAP.
-- ============================================================

BEGIN;

SET LOCAL search_path TO desenvolvimento, pg_catalog;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '5min';

-- ============================================================
-- 0. GUARDAS FAIL-CLOSED
-- ============================================================

DO $$
DECLARE
    v_existentes text[];
BEGIN
    IF current_database() <> 'fuga_jales_local_desenvolvimento' THEN
        RAISE EXCEPTION '057 ABORTADO: database incorreto: %', current_database();
    END IF;

    IF current_user <> 'postgres' THEN
        RAISE EXCEPTION '057 ABORTADO: principal administrativo inesperado: %', current_user;
    END IF;

    IF to_regnamespace('desenvolvimento') IS NULL THEN
        RAISE EXCEPTION '057 ABORTADO: schema desenvolvimento ausente.';
    END IF;

    SELECT array_agg(table_name ORDER BY table_name)
      INTO v_existentes
      FROM information_schema.tables
     WHERE table_schema = 'desenvolvimento'
       AND table_name IN ('operacao_resultado_perfil', 'operacao_resultado_definicao');

    IF COALESCE(array_length(v_existentes, 1), 0) > 0 THEN
        RAISE EXCEPTION '057 ABORTADO: objetos ja existentes: %.', array_to_string(v_existentes, ', ');
    END IF;

    IF to_regclass('desenvolvimento.operacao_producao_configuracao') IS NULL THEN
        RAISE EXCEPTION '057 ABORTADO: tabela referenciada operacao_producao_configuracao ausente.';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'fugapet_dev_app') THEN
        RAISE EXCEPTION '057 ABORTADO: papel fugapet_dev_app ausente.';
    END IF;
END
$$;

-- ============================================================
-- 1. operacao_resultado_perfil
-- ============================================================

CREATE TABLE desenvolvimento.operacao_resultado_perfil (
    codigo_perfil_resultado     bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo_configuracao_rota    bigint NOT NULL,
    ordem_ocorrencia_workcenter integer NOT NULL,
    ativo                       boolean NOT NULL DEFAULT true,
    criado_em                   timestamptz NOT NULL DEFAULT now(),
    criado_por                  character varying(80) NOT NULL DEFAULT CURRENT_USER,
    alterado_em                 timestamptz,
    alterado_por                character varying(80),

    CONSTRAINT operacao_resultado_perfil_pkey
        PRIMARY KEY (codigo_perfil_resultado),
    CONSTRAINT ck_resultado_perfil_ordem_ocorrencia
        CHECK (ordem_ocorrencia_workcenter > 0),
    CONSTRAINT fk_resultado_perfil_configuracao_rota
        FOREIGN KEY (codigo_configuracao_rota)
        REFERENCES desenvolvimento.operacao_producao_configuracao(codigo_configuracao)
        ON DELETE RESTRICT
);

CREATE INDEX ix_resultado_perfil_rota_ativo
    ON desenvolvimento.operacao_resultado_perfil
    USING btree (codigo_configuracao_rota, ativo);

-- Unico parcial: so uma ocorrencia ATIVA por rota e posicao no work center.
CREATE UNIQUE INDEX uq_resultado_perfil_ativo_ocorrencia
    ON desenvolvimento.operacao_resultado_perfil
    USING btree (codigo_configuracao_rota, ordem_ocorrencia_workcenter)
    WHERE (ativo IS TRUE);

-- ============================================================
-- 2. operacao_resultado_definicao
--    A coluna codigo_perfil_resultado e a ULTIMA de proposito: no Q ela foi
--    acrescentada depois da criacao da tabela, e a ordem foi preservada.
-- ============================================================

CREATE TABLE desenvolvimento.operacao_resultado_definicao (
    codigo_definicao        bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo_configuracao     bigint NOT NULL,
    codigo_item             character varying(50) NOT NULL,
    tipo                    character varying(40) NOT NULL,
    medida                  character varying(30) NOT NULL,
    referencia              numeric(18,3) NOT NULL,
    ordem_exibicao          integer NOT NULL,
    obrigatorio             boolean NOT NULL DEFAULT true,
    ativo                   boolean NOT NULL DEFAULT true,
    criado_em               timestamptz NOT NULL DEFAULT now(),
    criado_por              character varying(80) NOT NULL,
    alterado_em             timestamptz,
    alterado_por            character varying(80),
    codigo_perfil_resultado bigint,

    CONSTRAINT pk_operacao_resultado_definicao
        PRIMARY KEY (codigo_definicao),
    CONSTRAINT ck_resultado_definicao_codigo_item_nao_vazio
        CHECK (length(btrim((codigo_item)::text)) > 0),
    CONSTRAINT ck_resultado_definicao_medida_nao_vazia
        CHECK (length(btrim((medida)::text)) > 0),
    CONSTRAINT ck_resultado_definicao_ordem_positiva
        CHECK (ordem_exibicao > 0),
    CONSTRAINT ck_resultado_definicao_referencia_nao_negativa
        CHECK (referencia >= (0)::numeric),
    CONSTRAINT ck_resultado_definicao_tipo_nao_vazio
        CHECK (length(btrim((tipo)::text)) > 0),
    CONSTRAINT fk_resultado_definicao_configuracao
        FOREIGN KEY (codigo_configuracao)
        REFERENCES desenvolvimento.operacao_producao_configuracao(codigo_configuracao)
        ON DELETE RESTRICT,
    CONSTRAINT fk_resultado_definicao_perfil
        FOREIGN KEY (codigo_perfil_resultado)
        REFERENCES desenvolvimento.operacao_resultado_perfil(codigo_perfil_resultado)
        ON DELETE RESTRICT
);

CREATE INDEX ix_resultado_definicao_config_ativo
    ON desenvolvimento.operacao_resultado_definicao
    USING btree (codigo_configuracao, ativo);

CREATE INDEX ix_resultado_definicao_perfil_ativo
    ON desenvolvimento.operacao_resultado_definicao
    USING btree (codigo_perfil_resultado, ativo);

CREATE INDEX ix_resultado_definicao_tipo_medida
    ON desenvolvimento.operacao_resultado_definicao
    USING btree (tipo, medida)
    WHERE (ativo = true);

CREATE UNIQUE INDEX uq_resultado_definicao_ativa_perfil_item
    ON desenvolvimento.operacao_resultado_definicao
    USING btree (codigo_perfil_resultado, codigo_item)
    WHERE ((ativo IS TRUE) AND (codigo_perfil_resultado IS NOT NULL));

CREATE UNIQUE INDEX uq_resultado_definicao_ativa_perfil_ordem
    ON desenvolvimento.operacao_resultado_definicao
    USING btree (codigo_perfil_resultado, ordem_exibicao)
    WHERE ((ativo IS TRUE) AND (codigo_perfil_resultado IS NOT NULL));

-- ============================================================
-- 3. GRANT - identico ao Q: SELECT apenas
-- ============================================================

REVOKE ALL ON desenvolvimento.operacao_resultado_perfil FROM PUBLIC;
REVOKE ALL ON desenvolvimento.operacao_resultado_definicao FROM PUBLIC;

GRANT SELECT ON desenvolvimento.operacao_resultado_perfil TO fugapet_dev_app;
GRANT SELECT ON desenvolvimento.operacao_resultado_definicao TO fugapet_dev_app;

-- ============================================================
-- 4. POST-CHECKS FAIL-CLOSED
-- ============================================================

DO $$
DECLARE
    v_n        bigint;
    v_linhas_p bigint;
    v_linhas_d bigint;
BEGIN
    IF to_regclass('desenvolvimento.operacao_resultado_perfil') IS NULL
       OR to_regclass('desenvolvimento.operacao_resultado_definicao') IS NULL THEN
        RAISE EXCEPTION '057 POSTCHECK: tabela ausente apos o DDL.';
    END IF;

    -- Nenhuma FK pode ser em cascata: exclusao de configuracao nao apaga resultado.
    SELECT count(*) INTO v_n
      FROM pg_constraint
     WHERE connamespace = 'desenvolvimento'::regnamespace
       AND contype = 'f'
       AND confdeltype <> 'r'
       AND conrelid IN (
           'desenvolvimento.operacao_resultado_perfil'::regclass,
           'desenvolvimento.operacao_resultado_definicao'::regclass
       );
    IF v_n <> 0 THEN
        RAISE EXCEPTION '057 POSTCHECK: % FK sem ON DELETE RESTRICT.', v_n;
    END IF;

    -- As duas tabelas nascem vazias: este incremento nao copia dado do Q.
    EXECUTE 'SELECT count(*) FROM desenvolvimento.operacao_resultado_perfil' INTO v_linhas_p;
    EXECUTE 'SELECT count(*) FROM desenvolvimento.operacao_resultado_definicao' INTO v_linhas_d;
    IF v_linhas_p <> 0 OR v_linhas_d <> 0 THEN
        RAISE EXCEPTION '057 POSTCHECK: linhas inesperadas (perfil=%, definicao=%).', v_linhas_p, v_linhas_d;
    END IF;

    -- O runtime NAO pode ter escrita nestas tabelas.
    IF has_table_privilege('fugapet_dev_app', 'desenvolvimento.operacao_resultado_perfil', 'INSERT')
       OR has_table_privilege('fugapet_dev_app', 'desenvolvimento.operacao_resultado_perfil', 'UPDATE')
       OR has_table_privilege('fugapet_dev_app', 'desenvolvimento.operacao_resultado_perfil', 'DELETE')
       OR has_table_privilege('fugapet_dev_app', 'desenvolvimento.operacao_resultado_definicao', 'INSERT')
       OR has_table_privilege('fugapet_dev_app', 'desenvolvimento.operacao_resultado_definicao', 'UPDATE')
       OR has_table_privilege('fugapet_dev_app', 'desenvolvimento.operacao_resultado_definicao', 'DELETE') THEN
        RAISE EXCEPTION '057 POSTCHECK: runtime recebeu privilegio de escrita; esperado somente SELECT.';
    END IF;

    IF NOT has_table_privilege('fugapet_dev_app', 'desenvolvimento.operacao_resultado_perfil', 'SELECT')
       OR NOT has_table_privilege('fugapet_dev_app', 'desenvolvimento.operacao_resultado_definicao', 'SELECT') THEN
        RAISE EXCEPTION '057 POSTCHECK: runtime sem SELECT; o GRANT nao foi aplicado.';
    END IF;

    RAISE NOTICE 'POSTCHECK=OK  FKS=RESTRICT  LINHAS=0/0  GRANT=SELECT apenas';
END
$$;

COMMIT;

